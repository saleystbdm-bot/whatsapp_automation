import { createServer, Server } from 'http';

import { AddressInfo } from 'net';

import { INestApplication } from '@nestjs/common';

import { ConfigService } from '@nestjs/config';

import { DataSource } from 'typeorm';

import request from 'supertest';

import { GroupType } from '../src/common/enums/group-type.enum';

import { Group } from '../src/groups/entities/group.entity';

import { bootstrapTestApp, uniqueId } from './utils/bootstrap-app';

/**

 * Starts a throwaway local HTTP server standing in for n8n, so these

 * tests never call the real n8n cloud workflow. Each received request's

 * body is pushed onto `received`.

 */

function startMockN8n(

  behavior: 'ok' | 'fail' = 'ok',

): Promise<{ server: Server; url: string; received: unknown[] }> {

  const received: unknown[] = [];

  return new Promise((resolve) => {

    const server = createServer((req, res) => {

      let body = '';

      req.on('data', (chunk) => (body += chunk));

      req.on('end', () => {

        received.push({

          headers: req.headers,

          body: body ? JSON.parse(body) : null,

        });

        if (behavior === 'ok') {

          res.writeHead(200, { 'Content-Type': 'application/json' });

          res.end(JSON.stringify({ ok: true }));

        } else {

          res.writeHead(500);

          res.end('mock n8n failure');

        }

      });

    });

    server.listen(0, () => {

      const { port } = server.address() as AddressInfo;

      resolve({ server, url: `http\://127.0.0.1:${port}/mock-n8n`, received });

    });

  });

}

function inboundGroupMessage(overrides: Record<string, unknown> = {}) {

  return {

    id: uniqueId('wa-msg'),

    type: 'text',

    flow: 'inbound',

    chat: overrides.whatsappGroupId,

    from: overrides.whatsappGroupId,

    author: '919566800001@c.us',

    fromNumber: '+919566800001',

    body: 'Payment API is not working',

    date: new Date().toISOString(),

    meta: { isGroup: true },

    ...overrides,

  };

}

describe('Wassenger Webhook Receiver (e2e)', () => {

  let app: INestApplication;

  let dataSource: DataSource;

  let webhookSecret: string;

  let n8nSecret: string;

  let activeGroupId: string;

  let activeGroupWid: string;

  let inactiveGroupWid: string;

  const createdGroupIds: string[] = [];

  beforeAll(async () => {

    app = await bootstrapTestApp();

    dataSource = app.get(DataSource);

    const config = app.get(ConfigService);

    webhookSecret = config.get<string>('WASSENGER_WEBHOOK_SECRET', '');

    n8nSecret = config.get<string>('N8N_WEBHOOK_SHARED_SECRET', '');

    if (!webhookSecret) {

      throw new Error(

        'WASSENGER_WEBHOOK_SECRET must be set in the test environment',

      );

    }

    const groups = dataSource.getRepository(Group);

    const activeGroup = await groups.save(

      groups.create({

        whatsappGroupId: uniqueId('wa-active'),

        name: 'Webhook E2E Active Group',

        type: GroupType.INTERNAL,

        slaMinutes: 30,

        active: true,

      }),

    );

    activeGroupId = activeGroup.id;

    activeGroupWid = activeGroup.whatsappGroupId;

    createdGroupIds.push(activeGroup.id);

    const inactiveGroup = await groups.save(

      groups.create({

        whatsappGroupId: uniqueId('wa-inactive'),

        name: 'Webhook E2E Inactive Group',

        type: GroupType.INTERNAL,

        slaMinutes: 30,

        active: false,

      }),

    );

    inactiveGroupWid = inactiveGroup.whatsappGroupId;

    createdGroupIds.push(inactiveGroup.id);

  });

  afterAll(async () => {
    try {
      if (dataSource.isInitialized && createdGroupIds.length > 0) {
        // Delete dependent rows before deleting the test groups. These IDs
        // are generated by this test; do not clean up unrelated application data.
        await dataSource.query(
          'DELETE FROM notifications WHERE sla_id IN (SELECT id FROM sla_incidents WHERE group_id = ANY($1))',
          [createdGroupIds],
        );

        await dataSource.query(
          'DELETE FROM sla_incidents WHERE group_id = ANY($1)',
          [createdGroupIds],
        );

        await dataSource.query(
          'DELETE FROM issues WHERE group_id = ANY($1)',
          [createdGroupIds],
        );

        await dataSource.query(
          'DELETE FROM eod_reports WHERE group_id = ANY($1)',
          [createdGroupIds],
        );

        await dataSource.query(
          'DELETE FROM group_members WHERE group_id = ANY($1)',
          [createdGroupIds],
        );

        await dataSource.query(
          'DELETE FROM keywords WHERE group_id = ANY($1)',
          [createdGroupIds],
        );

        await dataSource.query(
          'DELETE FROM wassenger_webhook_events WHERE group_id = ANY($1)',
          [createdGroupIds],
        );

        await dataSource.query(
          'DELETE FROM groups WHERE id = ANY($1)',
          [createdGroupIds],
        );
      }
    } finally {
      await app.close();
    }
  });

  function post(body: Record<string, unknown>, secret = webhookSecret) {

    return request(app.getHttpServer())

      .post(`/webhooks/wassenger?secret=${encodeURIComponent(secret)}`)

      .send(body);

  }

  it('rejects a request with the wrong secret', async () => {

    await post({ id: uniqueId('wa-msg') }, 'wrong-secret').expect(401);

  });

  it('rejects a request with no secret', async () => {

    await request(app.getHttpServer())

      .post('/webhooks/wassenger')

      .send({ id: uniqueId('wa-msg') })

      .expect(401);

  });

  it('rejects a malformed payload (no message id) with 400', async () => {

    await post({ body: 'no id here' }).expect(400);

  });

  it('forwards a valid inbound group message for an active (monitored) group', async () => {

    const mock = await startMockN8n('ok');

    try {

      process.env.N8N_WASSENGER_FORWARD_URL = mock.url;

      const message = inboundGroupMessage({ whatsappGroupId: activeGroupWid });

      const response = await post(message).expect(200);

      expect(response.body).toEqual({ status: 'forwarded' });

      expect(mock.received).toHaveLength(1);

      const forwarded = mock.received[0] as {

        headers: Record<string, string>;

        body: Record<string, unknown>;

      };

      expect(forwarded.body.id).toBe(message.id);

      expect(

        (forwarded.body._monitoring as Record<string, unknown>).groupId,

      ).toBe(activeGroupId);

      if (n8nSecret) {

        expect(forwarded.headers['x-n8n-webhook-secret']).toBe(n8nSecret);

      }

      const row = await dataSource.query(

        'SELECT forwarded, group_id FROM wassenger_webhook_events WHERE external_message_id = $1',

        [message.id],

      );

      expect(row[0].forwarded).toBe(true);

      expect(row[0].group_id).toBe(activeGroupId);

    } finally {

      delete process.env.N8N_WASSENGER_FORWARD_URL;

      mock.server.close();

    }

  });

  it('does not forward a message for a group that is not monitored', async () => {

    const mock = await startMockN8n('ok');

    try {

      process.env.N8N_WASSENGER_FORWARD_URL = mock.url;

      const message = inboundGroupMessage({

        whatsappGroupId: inactiveGroupWid,

      });

      const response = await post(message).expect(200);

      expect(response.body).toEqual({

        status: 'skipped',

        reason: 'not_monitored',

      });

      expect(mock.received).toHaveLength(0);

    } finally {

      delete process.env.N8N_WASSENGER_FORWARD_URL;

      mock.server.close();

    }

  });

  it('does not forward a message for an unknown group', async () => {

    const mock = await startMockN8n('ok');

    try {

      process.env.N8N_WASSENGER_FORWARD_URL = mock.url;

      const message = inboundGroupMessage({

        whatsappGroupId: uniqueId('wa-unknown') + '@g.us',

      });

      const response = await post(message).expect(200);

      expect(response.body).toEqual({

        status: 'skipped',

        reason: 'unknown_group',

      });

      expect(mock.received).toHaveLength(0);

    } finally {

      delete process.env.N8N_WASSENGER_FORWARD_URL;

      mock.server.close();

    }

  });

  it('does not forward a private (non-group) message', async () => {

    const message = inboundGroupMessage({

      whatsappGroupId: activeGroupWid,

      meta: { isGroup: false },

    });

    const response = await post(message).expect(200);

    expect(response.body).toEqual({

      status: 'skipped',

      reason: 'private_message',

    });

  });

  it('does not forward an outbound message (loop prevention)', async () => {

    const message = inboundGroupMessage({

      whatsappGroupId: activeGroupWid,

      flow: 'outbound',

    });

    const response = await post(message).expect(200);

    expect(response.body).toEqual({ status: 'skipped', reason: 'outbound' });

  });

  it('duplicate delivery of an already-forwarded message is never forwarded twice', async () => {

    const mock = await startMockN8n('ok');

    try {

      process.env.N8N_WASSENGER_FORWARD_URL = mock.url;

      const message = inboundGroupMessage({ whatsappGroupId: activeGroupWid });

      const first = await post(message).expect(200);

      const second = await post(message).expect(200);

      expect(first.body).toEqual({ status: 'forwarded' });

      expect(second.body).toEqual({ status: 'duplicate' });

      expect(mock.received).toHaveLength(1); // not forwarded twice

      const rows = await dataSource.query(

        'SELECT id FROM wassenger_webhook_events WHERE external_message_id = $1',

        [message.id],

      );

      expect(rows).toHaveLength(1); // not duplicated in the audit table either

    } finally {

      delete process.env.N8N_WASSENGER_FORWARD_URL;

      mock.server.close();

    }

  });

  it('returns 503 when n8n forwarding fails, and retries succeed once n8n recovers', async () => {

    const failingMock = await startMockN8n('fail');

    const message = inboundGroupMessage({ whatsappGroupId: activeGroupWid });

    try {

      process.env.N8N_WASSENGER_FORWARD_URL = failingMock.url;

      await post(message).expect(503);

      const rows = await dataSource.query(

        'SELECT forwarded, skipped_reason FROM wassenger_webhook_events WHERE external_message_id = $1',

        [message.id],

      );

      expect(rows[0].forwarded).toBe(false);

      expect(rows[0].skipped_reason).toBe('forward_failed');

    } finally {

      failingMock.server.close();

    }

    // Wassenger redelivers the same message later; n8n is back up.

    const okMock = await startMockN8n('ok');

    try {

      process.env.N8N_WASSENGER_FORWARD_URL = okMock.url;

      const retry = await post(message).expect(200);

      expect(retry.body).toEqual({ status: 'forwarded' });

      expect(okMock.received).toHaveLength(1);

    } finally {

      delete process.env.N8N_WASSENGER_FORWARD_URL;

      okMock.server.close();

    }

  });

  it('does not affect existing event endpoints (e.g. POST /events/issues still works)', async () => {

    await request(app.getHttpServer())

      .post('/events/issues')

      .set('X-N8N-Webhook-Secret', n8nSecret)

      .send({

        messageId: uniqueId('msg'),

        groupId: activeGroupId,

        senderPhone: '+919566831192',

        message:

          'Regression check — events endpoint unaffected by the webhook receiver',

      })

      .expect(201);

  });

});
